int std14_width(const char *base_font, unsigned char code) {
    if (code < 0x20) return 0;
    if (!strncmp(base_font, "Courier", 7)) return 600;
    const unsigned short *t = W_HELVETICA;
    if (!strcmp(base_font, "Helvetica-Bold") || !strcmp(base_font, "Helvetica-BoldOblique"))
        t = W_HELVETICA_BOLD;
    else if (!strcmp(base_font, "Times-Roman"))
        t = W_TIMES_ROMAN;
    else if (!strcmp(base_font, "Times-Bold"))
        t = W_TIMES_BOLD;
    else if (!strcmp(base_font, "Times-Italic"))
        t = W_TIMES_ITALIC;
    return t[code - 0x20];
}
